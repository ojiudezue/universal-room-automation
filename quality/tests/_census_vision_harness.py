"""Census -> presence replay harness (census deconfliction CD1, crossing
vision P2; plan docs/planning/PLANNING_census_deconfliction.md §4).

Drives the REAL ``PersonCensus._async_update_census_locked`` (raw house path,
enhanced path, hold/decay, camera-dark latch, payload build) on a REAL Home
Assistant core over a scripted list of ticks, delivers the payload through the
REAL dispatcher to the REAL ``PresenceCoordinator._handle_census_update``, and
records, per tick:

* every pre-existing numeric / list field of the house result (trust view);
* the dispatched ``SIGNAL_CENSUS_UPDATED`` payload (all keys except the
  wall-clock ``count_as_of``);
* the presence fields the census feeds (the AWAY inputs) and the
  ``_run_inference`` triggers the update scheduled (spy: counted, not run);
* the real ``StateInferenceEngine.infer`` verdict from those presence fields
  (HOME_DAY, no zone occupied, the scripted all-residents-away flag), i.e.
  the tick on which AWAY fires;
* the native values of the four existing census sensors.

The golden (``fixtures/away_latency_golden_develop.json``) was generated by
``scripts/probes/gen_census_trust_golden.py`` on the develop merge-base
(3ec3f4d2) in the commit that precedes every production change of the branch
(INV-P2-AWAY-LATENCY provenance rule; a golden regenerated after the build is
a hollow oracle, Bug Class #62).

Time is frozen and advanced 30 s per tick (freezegun).
"""
